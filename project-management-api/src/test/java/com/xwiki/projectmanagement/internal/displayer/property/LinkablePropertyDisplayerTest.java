package com.xwiki.projectmanagement.internal.displayer.property;

import java.io.Reader;
import java.util.List;
import java.util.Map;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.RegisterExtension;
import org.xwiki.rendering.block.Block;
import org.xwiki.rendering.block.LinkBlock;
import org.xwiki.rendering.listener.reference.ResourceReference;
import org.xwiki.rendering.listener.reference.ResourceType;
import org.xwiki.rendering.parser.ParseException;
import org.xwiki.rendering.parser.Parser;
import org.xwiki.test.LogLevel;
import org.xwiki.test.junit5.LogCaptureExtension;

import com.xwiki.projectmanagement.model.Linkable;

import static com.xwiki.projectmanagement.internal.displayer.DisplayerTestUtils.assertWord;
import static com.xwiki.projectmanagement.internal.displayer.DisplayerTestUtils.mockPlainParser;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertInstanceOf;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.verifyNoInteractions;
import static org.mockito.Mockito.when;

/**
 * Unit tests for {@link LinkablePropertyDisplayer}.
 *
 * @version $Id$
 */
class LinkablePropertyDisplayerTest
{
    private static final String URL = "https://openproject.example.org/work_packages/42";

    @RegisterExtension
    private LogCaptureExtension logCapture = new LogCaptureExtension(LogLevel.WARN);

    private final Parser parser = mock(Parser.class);

    private final LinkablePropertyDisplayer displayer = new LinkablePropertyDisplayer(this.parser);

    @Test
    void displayIgnoresValuesThatAreNotMaps()
    {
        assertTrue(this.displayer.display(null, Map.of()).isEmpty());
        assertTrue(this.displayer.display("text", Map.of()).isEmpty());
        verifyNoInteractions(this.parser);
    }

    @Test
    void displayIgnoresLinkablesWithoutValue()
    {
        assertTrue(this.displayer.display(new Linkable(null, URL), Map.of()).isEmpty());
        assertTrue(this.displayer.display(new Linkable("", URL), Map.of()).isEmpty());
        verifyNoInteractions(this.parser);
    }

    @Test
    void displayLink() throws Exception
    {
        mockPlainParser(this.parser);

        List<Block> blocks = this.displayer.display(new Linkable("Fix the bug", URL), Map.of());

        assertEquals(1, blocks.size());
        LinkBlock link = assertInstanceOf(LinkBlock.class, blocks.get(0));
        assertEquals(new ResourceReference(URL, ResourceType.URL), link.getReference());
        assertEquals("_blank", link.getParameter("target"));
        assertFalse(link.isFreeStandingURI());
        // The paragraph generated by the parser is removed.
        assertWord("Fix the bug", link.getChildren());
    }

    @Test
    void displayAcceptsAnyMapHoldingTheLinkableKeys() throws Exception
    {
        mockPlainParser(this.parser);

        List<Block> blocks =
            this.displayer.display(Map.of(Linkable.KEY_VALUE, "42", Linkable.KEY_LOCATION, URL), Map.of());

        LinkBlock link = assertInstanceOf(LinkBlock.class, blocks.get(0));
        assertEquals(URL, link.getReference().getReference());
        assertWord("42", link.getChildren());
    }

    @Test
    void displayWithoutLocation() throws Exception
    {
        mockPlainParser(this.parser);

        assertWord("John Doe", this.displayer.display(new Linkable("John Doe", null), Map.of()));
        assertWord("John Doe", this.displayer.display(new Linkable("John Doe", ""), Map.of()));
    }

    @Test
    void displayWhenParsingFails() throws Exception
    {
        when(this.parser.parse(any(Reader.class))).thenThrow(new ParseException("boom"));

        List<Block> blocks = this.displayer.display(new Linkable("value", URL), Map.of());

        // The link is still displayed, but without label, so the URL is displayed instead.
        LinkBlock link = assertInstanceOf(LinkBlock.class, blocks.get(0));
        assertTrue(link.getChildren().isEmpty());
        assertTrue(link.isFreeStandingURI());
        assertEquals(URL, link.getReference().getReference());

        assertTrue(this.displayer.display(new Linkable("value", null), Map.of()).isEmpty());

        assertEquals("Failed to parse the value [value] of a linkable property. Cause: [ParseException: boom].",
            this.logCapture.getMessage(0));
        assertEquals("Failed to parse the value [value] of a linkable property. Cause: [ParseException: boom].",
            this.logCapture.getMessage(1));
    }
}
