import java.util.Arrays;

import javax.inject.Inject;
import javax.inject.Named;
import javax.inject.Singleton;

import org.apache.commons.lang3.exception.ExceptionUtils;
import org.quartz.SchedulerException;
import org.quartz.Trigger;
import org.slf4j.Logger;
import org.xwiki.component.annotation.Component;
import org.xwiki.model.reference.DocumentReference;
import org.xwiki.model.reference.EntityReference;
import org.xwiki.model.reference.EntityReferenceSerializer;
import org.xwiki.model.reference.LocalDocumentReference;
import org.xwiki.model.reference.WikiReference;
import org.xwiki.observation.AbstractEventListener;
import org.xwiki.observation.event.Event;
import org.xwiki.user.UserReferenceResolver;

import com.xpn.xwiki.XWikiContext;
import com.xpn.xwiki.XWikiException;
import com.xpn.xwiki.doc.XWikiDocument;
import com.xpn.xwiki.internal.event.XObjectAddedEvent;
import com.xpn.xwiki.internal.event.XObjectUpdatedEvent;
import com.xpn.xwiki.objects.BaseObject;
import com.xpn.xwiki.objects.BaseObjectReference;
import com.xpn.xwiki.plugin.scheduler.SchedulerPlugin;
import com.xwiki.projectmanagement.openproject.internal.AdminAuthorChecker;
import com.xwiki.projectmanagement.openproject.internal.displayer.StylingSetupManager;

/**
 * Event listener that watches changes on OpenProject configuration documents, schedules the
 * {@link StylingSetupManager} with the context user equal to the one that created the OpenProject configuration, and
 * triggers it so that the styles of the saved connection are generated without waiting for the next scheduled run.
 * This assures us that the job will execute with a user that is active in the wiki, and likely connected to
 * OpenProject (the statuses and types of the connections they aren't connected to are read without credentials). Only
 * the connections saved by a user with administration right on the wiki are taken into account, like in the
 * OpenProject configuration. The job of the wiki holding the saved connection is used.
 *
 * @version $Id$
 */
@Component
@Singleton
@Named("com.xwiki.projectmanagement.openproject.internal.listener.StyleSetupJobSchedulerListener")
public class StyleSetupJobSchedulerListener extends AbstractEventListener
{
    private static final String OPEN_PROJECT = "OpenProject";

    private static final EntityReference CLASS_OPEN_PROJECT =
        BaseObjectReference.any("OpenProject.Code.OpenProjectConnectionClass");

    private static final EntityReference DOC_SCHEDULER_JOB =
        new LocalDocumentReference(Arrays.asList(OPEN_PROJECT, "Code"), "StylingSetupJob");

    private static final String PLUGIN_SCHEDULER = "scheduler";

    private static final String JOB_CONTEXT_USER = "contextUser";

    private static final String SKIPPING_MESSAGE = "Not using the job [{}] ";

    @Inject
    private Logger logger;

    @Inject
    @Named("compact")
    private EntityReferenceSerializer<String> serializer;

    @Inject
    private AdminAuthorChecker adminAuthorChecker;

    @Inject
    @Named("document")
    private UserReferenceResolver<DocumentReference> userReferenceResolver;

    /**
     * Default constructor.
     */
    public StyleSetupJobSchedulerListener()
    {
        super(StyleSetupJobSchedulerListener.class.getName(),
            Arrays.asList(new XObjectAddedEvent(CLASS_OPEN_PROJECT), new XObjectUpdatedEvent(CLASS_OPEN_PROJECT)));
    }

    @Override
    public void onEvent(Event event, Object source, Object data)
    {
        XWikiDocument connection = (XWikiDocument) source;
        XWikiContext context = (XWikiContext) data;
        // The styles of a connection are generated by the job of the wiki holding it.
        WikiReference currentWiki = context.getWikiReference();
        context.setWikiReference(connection.getDocumentReference().getWikiReference());
        try {
            updateAndTriggerJob(connection, context);
        } finally {
            context.setWikiReference(currentWiki);
        }
    }

    private void updateAndTriggerJob(XWikiDocument connection, XWikiContext context)
    {
        // The job runs as the user who saved the connection: it must be allowed to generate the styling.
        DocumentReference connectionAuthor = this.adminAuthorChecker.getMetadataAuthor(connection);
        if (connectionAuthor == null
            || !this.adminAuthorChecker.isAdmin(connectionAuthor, context.getWikiReference()))
        {
            this.logger.debug(SKIPPING_MESSAGE + "since the OpenProject connection stored on [{}] wasn't saved by a "
                + "user with administration right on the wiki.", DOC_SCHEDULER_JOB, connection.getDocumentReference());
            return;
        }

        SchedulerPlugin scheduler =
            (SchedulerPlugin) context.getWiki().getPluginManager().getPlugin(PLUGIN_SCHEDULER);
        try {
            // Work on a copy of the cached document.
            XWikiDocument jobDoc = context.getWiki().getDocument(DOC_SCHEDULER_JOB, context).clone();
            BaseObject job = jobDoc.getXObject(SchedulerPlugin.XWIKI_JOB_CLASSREFERENCE);
            if (job == null) {
                // E.g. a connection imported before the job page.
                this.logger.debug(SKIPPING_MESSAGE + "since it doesn't exist on the wiki [{}].", DOC_SCHEDULER_JOB,
                    context.getWikiId());
                return;
            }
            Trigger.TriggerState state = scheduler.getJobStatus(job, context).getQuartzState();
            if (state != Trigger.TriggerState.NORMAL && state != Trigger.TriggerState.NONE) {
                // E.g. paused by an administrator, or already running.
                this.logger.debug(SKIPPING_MESSAGE + "since its state is [{}].", DOC_SCHEDULER_JOB, state);
                return;
            }
            maybeChangeJobUserAndReschedule(scheduler, jobDoc, job, state, connectionAuthor, context);
            // Generate the styles of the saved connection now rather than at the next scheduled run. The job runs in a
            // scheduler thread, so the save isn't delayed by the requests to OpenProject, nor failed by their errors.
            scheduler.triggerJob(job, context);
        } catch (XWikiException | SchedulerException e) {
            this.logger.warn("Failed to set the context user [{}] for the job [{}] and trigger it. Cause: [{}].",
                connectionAuthor, DOC_SCHEDULER_JOB, ExceptionUtils.getRootCauseMessage(e));
        }
    }

    private void maybeChangeJobUserAndReschedule(SchedulerPlugin scheduler, XWikiDocument jobDoc, BaseObject job,
        Trigger.TriggerState state, DocumentReference connectionAuthor, XWikiContext context) throws XWikiException
    {
        String connectionUser = this.serializer.serialize(connectionAuthor);
        boolean scheduled = state == Trigger.TriggerState.NORMAL;
        // Skip if the job is scheduled and its user is already set to this one.
        if (scheduled && connectionUser.equals(job.getStringValue(JOB_CONTEXT_USER))) {
            return;
        }
        if (scheduled) {
            scheduler.unscheduleJob(job, context);
        }
        job.setStringValue(JOB_CONTEXT_USER, connectionUser);
        // Record who changed the job but keep its effective author, whose rights the job script runs with.
        jobDoc.getAuthors().setOriginalMetadataAuthor(this.userReferenceResolver.resolve(connectionAuthor));
        context.getWiki().saveDocument(jobDoc, String.format("Updated context user to [%s].", connectionAuthor),
            context);
        scheduler.scheduleJob(job, context);
    }
}
