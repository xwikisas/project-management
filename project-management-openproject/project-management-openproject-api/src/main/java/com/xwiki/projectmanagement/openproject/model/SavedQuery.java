package com.xwiki.projectmanagement.openproject.model;

import org.apache.commons.lang3.StringUtils;
import org.xwiki.stability.Unstable;

import com.fasterxml.jackson.databind.JsonNode;

/**
 * A saved query of OpenProject (a work package list saved with a name), as described by the OpenProject API
 * ({@code /api/v3/queries/{id}}).
 *
 * @version $Id$
 * @since 1.5.0
 */
@Unstable
public class SavedQuery
{
    private static final String LINKS = "_links";

    private static final String HREF = "href";

    private final String name;

    private final String projectName;

    private final String resultsUrl;

    /**
     * @param queryNode the saved query, as returned by the OpenProject API
     */
    public SavedQuery(JsonNode queryNode)
    {
        this.name = queryNode.path("name").asText();
        JsonNode project = queryNode.path(LINKS).path("project");
        String projectHref = project.path(HREF).textValue();
        this.projectName = StringUtils.isEmpty(projectHref) ? null : project.path("title").textValue();
        this.resultsUrl = queryNode.path(LINKS).path("results").path(HREF).asText();
    }

    /**
     * @return the name of the saved query
     */
    public String getName()
    {
        return this.name;
    }

    /**
     * @return the name of the project the saved query belongs to, or {@code null} when it lists the work packages of
     *     all the projects
     */
    public String getProjectName()
    {
        return this.projectName;
    }

    /**
     * @return the link returning the work packages of the saved query, generated by OpenProject with the filters and
     *     the sorting of the query, or an empty string if it has none
     */
    public String getResultsUrl()
    {
        return this.resultsUrl;
    }
}
